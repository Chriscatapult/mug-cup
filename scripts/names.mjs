// Words and phrases peeled off the front and back of formal names.
const PREFIX = /^(Football Club|Fußballclub|Fussballclub|Futbol Club|Fútbol Club|Club Atlético|Club Atletico|Club Deportivo|Club Sportivo|Club Social y Deportivo|Asociación Deportivo|Asociación Atlética|Associação|Associazione Sportiva|Unione Sportiva|Società Sportiva|Sport Club|Sporting Clube de|Clube de Regatas do|Clube|Esporte Clube|Sociedade Esportiva|Athlitiki Enosi|Athlitikos Omilos|Idrottsföreningen|Idrottsforeningen|Idrætsforening|Royal|Koninklijke|K\.?|R\.?|FC|CF|SC|AC|AS|US|SS|SSC|CD|CA|CS|RC|RCD|UD|SD|SV|VfB|VfL|TSG|FK|PFK|NK|HNK|GNK|SK|BK|IF|IK|AFC|ACF|OGC|LOSC|KAA|KRC|KV|SV|GD|1\.)\s+/i;
const SUFFIX = /\s+(Football Club|Futebol Clube|Fútbol Club|Fotballforening|Ballklubb|Idrettslag|Calcio|FC|CF|SC|AFC|KV|BK|FF|IF|SK|S\.A\.D\.?|a\.s\.|\d{4})$/i;

export function cleanName(name, code) {
  if (OVERRIDES[code]) return OVERRIDES[code];
  let n = name.replace(/\s+/g, ' ').trim();
  for (let k = 0; k < 4; k++) {
    const before = n;
    n = n.replace(/,$/, '').replace(SUFFIX, '').trim();
    if (n.split(' ').length > 1) n = n.replace(PREFIX, '').trim();
    if (n === before) break;
  }
  return n;
}

// Used to match the same club across the data and the hand-written packets.
export function key(name) {
  return name.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/&/g, 'and').replace(/\b(fc|afc|cf|sc|the|football club)\b/g, '').replace(/[^a-z0-9]+/g, '');
}
